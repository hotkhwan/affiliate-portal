const tables: Record<Exclude<Locale, 'th'>, Record<string, string>> = { en, zh }

export function translate(locale: Locale, source: string, values: Record<string, string | number> = {}): string {
  let result = locale === 'th' ? source : tables[locale][source] || source
  for (const [key, value] of Object.entries(values)) result = result.replaceAll(`{${key}}`, String(value))
  return result
}

export function detectLocale(value: string | readonly string[] | undefined): Locale {
  const languages = typeof value === 'string' ? [value] : value || []
  for (const language of languages) {
    const normalized = language.toLowerCase()
    if (normalized.startsWith('zh')) return 'zh'
    if (normalized.startsWith('en')) return 'en'
    if (normalized.startsWith('th')) return 'th'
  }
  return 'th'
}
